/**
 * Create the Devnet "mirror" mints the deployed program issues so a Devnet wallet
 * can genuinely hold the (mainnet-only) PreStocks basket on-chain.
 *
 * For each non-cash basket symbol → one classic SPL mint (9 decimals), plus one
 * USDC mirror (6 decimals). Mint authority = the program vault PDA ([b"vault"]),
 * so ONLY the program (via subscribe / faucet_usdc CPIs) can mint — no key holds
 * it. Freeze authority = none. Writes web/lib/devnet-mints.json for the web app.
 *
 * Idempotent: a mint already recorded in the registry that still exists on-chain
 * is reused; only missing ones are created. Safe to re-run.
 *
 * Env: ANCHOR_WALLET (payer/creator keypair, needs Devnet SOL),
 *      HELIUS_RPC | ANCHOR_PROVIDER_URL (RPC, default api.devnet.solana.com).
 */
const fs = require("fs");
const path = require("path");
const anchor = require("@coral-xyz/anchor");
const { createMint, TOKEN_PROGRAM_ID } = require("@solana/spl-token");
const { getBasket } = require("../lib/baskets");
const { listApprovedAssets } = require("../lib/asset-registry");
const { Connection, PublicKey, Keypair } = anchor.web3;

const RPC = process.env.HELIUS_RPC || process.env.ANCHOR_PROVIDER_URL || "https://api.devnet.solana.com";
const WALLET = process.env.ANCHOR_WALLET;
if (!WALLET) throw new Error("Set ANCHOR_WALLET to the deploy keypair path");

const PROGRAM_ID = new PublicKey("EVx3g8ooCpshuemiNz3bt3vqoYapu7XjPab86BbnrgYN");
const BASKETS = ["ai-infrastructure", "space-deep-tech"];
const USDC_DECIMALS = 6;
const STOCK_DECIMALS = 9;
const REGISTRY_PATH = path.join(__dirname, "..", "web", "lib", "devnet-mints.json");

const vaultPda = PublicKey.findProgramAddressSync([Buffer.from("vault")], PROGRAM_ID)[0];

function loadRegistry() {
  try { return JSON.parse(fs.readFileSync(REGISTRY_PATH, "utf-8")); }
  catch { return null; }
}
async function existsOnChain(connection, addr) {
  if (!addr) return false;
  try { return Boolean(await connection.getAccountInfo(new PublicKey(addr))); }
  catch { return false; }
}
// __SEED_MINTS_MAIN__
async function main() {
  const connection = new Connection(RPC, "confirmed");
  const payer = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(WALLET, "utf-8"))));
  console.log("payer/creator:", payer.publicKey.toBase58());
  console.log("vault (mint authority):", vaultPda.toBase58());

  const prev = loadRegistry() || {};
  const prevAssets = prev.assets || {};

  // Real mainnet mint per symbol — recorded for reference only (never minted here).
  const mainnetOf = {};
  for (const a of listApprovedAssets()) mainnetOf[a.symbol] = a.mint;

  // Unique non-cash symbols across the catalogue baskets.
  const symbols = new Set();
  for (const id of BASKETS) for (const c of getBasket(id).constituents) if (c.symbol !== "USDC") symbols.add(c.symbol);

  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  // createMint can hit transient RPC races on Devnet ("Blockhash not found",
  // rate limits, node lag). Retry with a fresh blockhash before giving up.
  const mkMint = async (decimals) => {
    let lastErr;
    for (let attempt = 1; attempt <= 6; attempt++) {
      try {
        return await createMint(connection, payer, vaultPda, null, decimals, undefined, { commitment: "confirmed" }, TOKEN_PROGRAM_ID);
      } catch (e) {
        lastErr = e;
        const msg = String((e && e.message) || e);
        if (!/Blockhash not found|block height exceeded|Node is behind|429|Too Many Requests|Timed out|timeout/i.test(msg)) throw e;
        console.log(`  … transient RPC error (attempt ${attempt}), retrying: ${msg}`);
        await sleep(1500 * attempt);
      }
    }
    throw lastErr;
  };

  const REGISTRY_COMMENT =
    "Devnet mirror-mint registry. Generated by tests/seed-devnet-mints.js — do not hand-edit mint addresses.";
  // Persist after every mint so a partial run is resumable — already-created
  // mints are reused on the next run instead of orphaned.
  const flush = (usdc, assetsSoFar) => {
    fs.writeFileSync(
      REGISTRY_PATH,
      JSON.stringify(
        {
          _comment: REGISTRY_COMMENT,
          programId: PROGRAM_ID.toBase58(),
          vault: vaultPda.toBase58(),
          usdc: { mint: usdc, decimals: USDC_DECIMALS },
          assets: assetsSoFar,
        },
        null,
        2,
      ) + "\n",
    );
  };

  // USDC mirror (reuse if still on-chain).
  let usdcMint = prev.usdc && prev.usdc.mint;
  if (await existsOnChain(connection, usdcMint)) console.log(`USDC   reuse  ${usdcMint}`);
  else { usdcMint = (await mkMint(USDC_DECIMALS)).toBase58(); console.log(`USDC   create ${usdcMint} (${USDC_DECIMALS} dp)`); }

  const assets = {};
  flush(usdcMint, assets);
  for (const sym of symbols) {
    let mint = prevAssets[sym] && prevAssets[sym].mint;
    if (await existsOnChain(connection, mint)) console.log(`${sym.padEnd(6)} reuse  ${mint}`);
    else { mint = (await mkMint(STOCK_DECIMALS)).toBase58(); console.log(`${sym.padEnd(6)} create ${mint} (${STOCK_DECIMALS} dp)`); }
    assets[sym] = { mint, decimals: STOCK_DECIMALS, mainnetMint: mainnetOf[sym] || null };
    flush(usdcMint, assets);
  }

  console.log(`\nWrote ${REGISTRY_PATH}`);
  console.log(`Mirror mints ready: USDC + ${Object.keys(assets).length} assets.`);
  console.log("Next: run tests/seed-onchain-strategy.js so each strategy's asset PDAs bind to these mirror mints.");
}

main().catch((e) => { console.error(e); process.exit(1); });
